def build_locked_v2_eval_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    index = 1
    for tag, examples in SCENARIOS.items():
        for prompt, expected in examples:
                row_id = f"gp4_vi_locked_{tag}_{index:06d}"
                rows.append(_row(row_id, prompt, expected, tag))
                index += 1
    return rows


def write_locked_v2_eval(path: Path) -> None:
    write_jsonl(path, build_locked_v2_eval_rows())


def _row(
    row_id: str,
    prompt: str,
    expected: dict[str, Any],
    tag: str,
) -> dict[str, Any]:
    return {
        "id": row_id,
        "messages": [
            {"role": "system", "content": SEMANTIC_IR_SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
            {
                "role": "assistant",
                "content": json.dumps(
                    expected,
                    ensure_ascii=False,
                    separators=(",", ":"),
                ),
            },
        ],
        "expected_json": expected,
        "metadata": {
            "language": "vi" if prompt in VI_PROMPTS else "en",
            "task_type": "hard_negative" if "error" in expected else "normal",
            "source": "eval",
            "source_dataset": "locked_eval",
            "safety_class": "unsafe_rejected" if "error" in expected else "safe_motion_plan",
            "requires_perception": False,
            "scenario_tags": [tag],
        },
    }
